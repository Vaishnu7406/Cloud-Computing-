# ------------------------------------------------------------------ loading
def _mtime(p):
    return p.stat().st_mtime if p.exists() else 0


@st.cache_resource
def load_artifacts(stamp):
    model = joblib.load(du.MODEL_DIR / "position_model.joblib")
    with open(du.MODEL_DIR / "metadata.json", encoding="utf-8") as fh:
        meta = json.load(fh)
    return model, meta


@st.cache_data
def load_data(path, stamp):
    return pd.read_csv(path)


@st.cache_data
def load_test_predictions(stamp):
    return pd.read_csv(du.MODEL_DIR / "test_predictions.csv")


def get_artifacts():
    mp, mj = du.MODEL_DIR / "position_model.joblib", du.MODEL_DIR / "metadata.json"
    if not (mp.exists() and mj.exists()):
        return None, None, "Trained model not found."
    try:
        model, meta = load_artifacts((_mtime(mp), _mtime(mj)))
        return model, meta, None
    except Exception as exc:
        return None, None, f"Could not load the saved model ({exc}). Re-train it."


def get_dataset(meta):
    path = du.Path(meta["data_file"])
    if not path.is_absolute():
        path = du.BASE_DIR / path
    if not path.exists():
        return None
    return load_data(str(path), _mtime(path))


def train_now():
    import train_model
    with st.spinner("Training models (this takes under a minute) ..."):
        train_model.main()
    load_artifacts.clear(); load_data.clear(); load_test_predictions.clear()
    st.rerun()


