# --- prediction page helpers
def _default(f):
    return round(meta["feature_stats"][f]["median"], 3)


def reset_inputs():
    for f in meta["features"]:
        st.session_state[f"inp_{f}"] = _default(f)
    st.session_state.pop("last", None)
    st.session_state.pop("sample", None)


def load_random_sample():
    df = get_dataset(meta)
    if df is None:
        return
    row = df.sample(1).iloc[0]
    for f in meta["features"]:
        st.session_state[f"inp_{f}"] = float(round(row[f], 4))
    st.session_state["sample"] = {"signals": {f: float(round(row[f], 4)) for f in meta["features"]},
                                  "truth": [float(row[t]) for t in meta["targets"]]}


def page_predict():
    st.title("Indoor Position Prediction")
    synthetic_banner()
    feats, targs = meta["features"], meta["targets"]
    for f in feats:
        st.session_state.setdefault(f"inp_{f}", _default(f))

    st.write("Enter the signal strength measured from each light source, then press **Predict Indoor Position**. "
             "The model only runs when you press the button, and it uses exactly the values in the boxes.")
    fs = meta["feature_stats"]
    st.caption(f"Unit: {meta['units']['signal']}. Values must be 0 or higher. Values outside the range seen in "
               "training are accepted but flagged, because the model has to extrapolate.")
    st.dataframe(pd.DataFrame({f: {"Min in training data": fs[f]["min"], "Max in training data": fs[f]["max"]}
                               for f in feats}).round(3))

    with st.form("predict_form"):
        cols = st.columns(min(len(feats), 4))
        vals = {}
        for i, f in enumerate(feats):
            vals[f] = cols[i % len(cols)].number_input(
                f"{f} signal", min_value=0.0, max_value=max(1000.0, fs[f]["max"] * 10), step=0.5,
                format="%.4f", key=f"inp_{f}", help=f"Training range {fs[f]['min']:.2f} to {fs[f]['max']:.2f}")
        submitted = st.form_submit_button("Predict Indoor Position", type="primary")

    b1, b2, _ = st.columns([1, 1.4, 3])
    b1.button("Reset inputs", on_click=reset_inputs)
    b2.button("Fill with a random dataset row", on_click=load_random_sample,
              help="Only fills the boxes (it does not predict). The true position is shown after you predict.")

    if submitted:
        errors = [f"{f} must be a finite number of 0 or more." for f, v in vals.items()
                  if v is None or not np.isfinite(v) or v < 0]
        if not errors and all(v == 0 for v in vals.values()):
            errors.append("All signals are 0, which means no light was detected. Enter at least one signal.")
        if errors:
            for e in errors:
                st.error(e)
        else:
            try:
                X_in = pd.DataFrame([[float(vals[f]) for f in feats]], columns=feats)   # training column order
                px_, py_ = [float(v) for v in model.predict(X_in)[0]]
            except Exception as exc:
                st.error(f"Prediction failed: {exc}")
            else:
                sample = st.session_state.get("sample")
                truth = sample["truth"] if sample and all(
                    abs(sample["signals"][f] - vals[f]) < 1e-9 for f in feats) else None
                rec = {"time": datetime.now().strftime("%H:%M:%S"), "inputs": dict(X_in.iloc[0]),
                       "pred": (px_, py_), "truth": truth,
                       "outside": [f for f in feats if not fs[f]["min"] <= vals[f] <= fs[f]["max"]]}
                st.session_state["last"] = rec
                st.session_state.setdefault("history", []).append(rec)

    rec = st.session_state.get("last")
    if rec:
        st.subheader("Result")
        c = st.columns(2)
        c[0].metric(f"Predicted {targs[0]}", f"{rec['pred'][0]:.3f} {meta['units']['position']}")
        c[1].metric(f"Predicted {targs[1]}", f"{rec['pred'][1]:.3f} {meta['units']['position']}")
        if rec["outside"]:
            st.warning(f"Input outside the training range for: {', '.join(rec['outside'])}. Treat this "
                       "prediction with caution.")
        tx, ty = (meta["target_stats"][t] for t in targs)
        if not (tx["min"] <= rec["pred"][0] <= tx["max"] and ty["min"] <= rec["pred"][1] <= ty["max"]):
            st.warning("The predicted position is outside the coordinate area covered by the dataset.")
        if rec["truth"]:
            e = float(np.hypot(rec["pred"][0] - rec["truth"][0], rec["pred"][1] - rec["truth"][1]))
            st.info(f"These inputs came from a dataset row with true position "
                    f"({rec['truth'][0]:.3f}, {rec['truth'][1]:.3f}) m. Error: {e:.3f} m. "
                    "(That row was part of the data, so this is a demo, not a fair accuracy test.)")
        st.write("**Exact input values sent to the model (at " + rec["time"] + "):**")
        st.dataframe(pd.DataFrame([rec["inputs"]]), hide_index=True)
        st.button("Show on map", on_click=go_to, args=("Position Visualization",))
    else:
        st.info("No prediction yet. Enter values and press the button.")

    hist = st.session_state.get("history", [])
    if hist:
        with st.expander(f"Prediction history ({len(hist)})"):
            st.dataframe(pd.DataFrame([{"time": h["time"], **h["inputs"], "pred_X": round(h["pred"][0], 3),
                                        "pred_Y": round(h["pred"][1], 3)} for h in hist]),
                         hide_index=True)
            if st.button("Clear history"):
                st.session_state["history"] = []
                st.rerun()


def page_viz():
    st.title("Position Visualization")
    synthetic_banner()
    df = get_dataset(meta)
    X, Y = meta["targets"]
    tx, ty = meta["target_stats"][X], meta["target_stats"][Y]
    c = st.columns(3)
    show_ref = c[0].checkbox("Reference samples", value=True)
    show_hist = c[1].checkbox("Earlier predictions", value=True)
    show_led = c[2].checkbox("Simulated LED positions", value=True, disabled=not meta["is_synthetic"])

    fig = go.Figure()
    fig.add_shape(type="rect", x0=tx["min"], x1=tx["max"], y0=ty["min"], y1=ty["max"],
                  line=dict(color=SLATE, dash="dot"), fillcolor="rgba(15,92,110,0.04)")
    if show_ref and df is not None:
        s = df.sample(min(1500, len(df)), random_state=3)
        fig.add_trace(go.Scatter(x=s[X], y=s[Y], mode="markers", name="Reference samples",
                                 marker=dict(size=4, color="#8FB3BF", opacity=0.6),
                                 hovertemplate=f"{X}=%{{x:.2f}} m<br>{Y}=%{{y:.2f}} m<extra>reference</extra>"))
    if show_led and meta["is_synthetic"]:
        led = meta["simulation"]["led_xy_m"]
        fig.add_trace(go.Scatter(x=[p[0] for p in led], y=[p[1] for p in led], mode="markers+text",
                                 name="Simulated LEDs", text=[f"L{i+1}" for i in range(len(led))],
                                 textposition="top center",
                                 marker=dict(size=14, symbol="square", color=AMBER, line=dict(width=1, color=INK)),
                                 hovertemplate="LED at (%{x:.2f}, %{y:.2f}) m<extra></extra>"))
    hist = st.session_state.get("history", [])
    if show_hist and len(hist) > 1:
        old = hist[:-1]
        fig.add_trace(go.Scatter(x=[h["pred"][0] for h in old], y=[h["pred"][1] for h in old], mode="markers",
                                 name="Earlier predictions", marker=dict(size=8, color=SLATE, symbol="x")))
    rec = st.session_state.get("last")
    if rec:
        fig.add_trace(go.Scatter(x=[rec["pred"][0]], y=[rec["pred"][1]], mode="markers", name="Predicted position",
                                 marker=dict(size=20, symbol="star", color="#D1342F", line=dict(width=1.5, color=INK)),
                                 hovertemplate=f"Predicted<br>{X}=%{{x:.3f}} m<br>{Y}=%{{y:.3f}} m<extra></extra>"))
        if rec["truth"]:
            fig.add_trace(go.Scatter(x=[rec["truth"][0]], y=[rec["truth"][1]], mode="markers", name="True position",
                                     marker=dict(size=12, symbol="circle-open", color=TEAL, line=dict(width=3))))
    pad = 0.3
    fig.update_layout(height=640, plot_bgcolor="#fff", legend=dict(orientation="h", y=-0.12),
                      xaxis=dict(title=f"{X} (m)", range=[tx["min"] - pad, tx["max"] + pad], showgrid=True, gridcolor="#DDE6EB"),
                      yaxis=dict(title=f"{Y} (m)", range=[ty["min"] - pad, ty["max"] + pad], showgrid=True, gridcolor="#DDE6EB",
                                 scaleanchor="x", scaleratio=1))
    st.plotly_chart(fig)
    st.caption("The dotted rectangle is the coordinate area covered by the dataset. It is a conceptual layout, "
               "not a real floor plan." + (" LED positions are those assumed by the simulation." if meta["is_synthetic"] else ""))
    if not rec:
        st.info("No prediction yet.")
        st.button("Go to Position Prediction", type="primary", on_click=go_to, args=("Position Prediction",))
    else:
        st.write(f"Predicted position: **({rec['pred'][0]:.3f}, {rec['pred'][1]:.3f}) m**")


